"""The reference document, generated from the declarations (``python3 -m
flow docs``): design-file keys (sipath.schema), step parameters (sipath.params),
run configuration and PDK description keys."""
from __future__ import annotations

import os

from . import params, schema
from .pdk import PDK_KEYS

HEADER = """# SiPath reference

Generated by `python3 -m sipath docs` from the declarations in `sipath/schema.py`
(design file) and `sipath/params.py` (step parameters); do not edit by hand.
A design file is checked against these before anything runs: unknown keys,
wrong types, values not allowed and missing required keys are errors.
"""


def text() -> str:
    cfg = ["## Run configuration", "",
           "Design file `config:`, a `--config` file, or `FLOW_<KEY>` environment variables (sipath.config).", "",
           "| key | type | description |", "|---|---|---|"]
    cfg += [f"| `{k}` | {f.type} | {f.doc} |" for k, f in schema.CONFIG.items()]
    pdk = ["## PDK description keys", "",
           "Top-level keys of a PDK description (`sipath/pdks/*.yaml`); others are errors. "
           "`step_defaults` takes the same tables as a design file's.", "",
           ", ".join(f"`{k}`" for k in sorted(PDK_KEYS)), ""]
    return "\n".join([HEADER, schema.markdown(), params.markdown(), *cfg, "", *pdk])


def write(path: str) -> str:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        f.write(text())
    return path
