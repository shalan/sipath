"""Pad-ring genericity check on a second IO library: IHP SG13G2 (ORFS).

    python3 -m sipath.examples.ihp_ring [workdir]

A small die (16 pads, an inverter between an input and an output pad) run
through the floorplan step only. Nothing about the IHP IO cells is given:
corner site, row depths, corner rotation, pad rotations and the ring's bus
pins are all derived from the library, as for sky130. IHP pads have their
core pins on the opposite side to sky130's and a different corner cell, so
the same code must pick different rotations and still close the ring.
"""
from __future__ import annotations

import os
import sys

from .. import steps
from ..design import Design, Pad
from ..netlist import Module
from ..pdk import Pdk, load as load_pdk
from ..scheduler import Flow
from ..session import OpenRoadSession, find_openroad
from .designs import INPUTS, changed_only

IO = "sg13g2_"
PADS = {  # edge -> (port or name, master); satisfies sipath.padplan rules
    "west": [("in0", "IOPadIn"), ("iovdd_w", "IOPadIOVdd"), ("iovss_w", "IOPadIOVss"), ("vdd_w", "IOPadVdd"),
             ("vss_w", "IOPadVss")],
    "east": [("out0", "IOPadOut4mA"), ("iovdd_e", "IOPadIOVdd"), ("iovss_e", "IOPadIOVss"), ("vdd_e", "IOPadVdd"),
             ("vss_e", "IOPadVss")],
    "north": [("in1", "IOPadIn"), ("iovdd_n", "IOPadIOVdd"), ("iovss_n", "IOPadIOVss")],
    "south": [("out1", "IOPadOut4mA"), ("iovdd_s", "IOPadIOVdd"), ("iovss_s", "IOPadIOVss")],
}


def ihp_pdk(platforms: str) -> Pdk:
    return load_pdk("ihp-sg13g2", platforms=platforms)


def make_design(pdk: Pdk, out_dir=INPUTS) -> Design:
    m = Module("ihp_ring")
    for port in ("in0", "in1", "out0", "out1"):
        m.port(port, "inout")
    pads, kinds = [], {}
    core = {}
    for edge, lst in PADS.items():
        for order, (name, master) in enumerate(lst):
            inst = f"pad_{name}"
            pads.append(Pad(inst, edge, order, IO + master))
            if master == "IOPadIn":
                core[name] = m.wire(f"core.{name}")
                m.inst(inst, IO + master, pad=name, p2c=core[name])
                kinds[inst] = "input"
            elif master == "IOPadOut4mA":
                core[name] = m.wire(f"core.{name}")
                m.inst(inst, IO + master, pad=name, c2p=core[name])
                kinds[inst] = "output"
            else:
                m.inst(inst, IO + master)
    m.inst("u_inv0", "sg13g2_inv_1", A=core["in0"], Y=core["out0"])
    m.inst("u_inv1", "sg13g2_inv_1", A=core["in1"], Y=core["out1"])
    os.makedirs(out_dir, exist_ok=True)
    netlist, sdc = os.path.join(out_dir, "ihp_ring.v"), os.path.join(out_dir, "ihp_ring.sdc")
    with changed_only(netlist) as f:
        f.write("// generated by sipath.examples.ihp_ring\n" + m.to_verilog())
    with changed_only(sdc) as f:
        f.write("# no clocks: pad-ring check only\n")
    return Design(
        name="ihp_ring", top="ihp_ring", mode="die", netlist=netlist, sdc=sdc,
        die=(0.0, 0.0, 1000.0, 1000.0), core_margin=220.0,
        pads=pads, pad_kinds=kinds,
        is_core=True,  # corner and filler cells, IO LEFs and layers from the PDK description
    ).resolve(pdk)


def run(workdir: str, runner=None) -> Flow:
    runner = runner or find_openroad()
    if runner is None:
        raise FileNotFoundError("OpenROAD not available")
    pdk = ihp_pdk(runner.platform_root())
    design = make_design(pdk)
    runner.mount(workdir, *design.input_files(), *pdk.files())
    flow = Flow(design, pdk, workdir, lambda d: OpenRoadSession(d, runner), runner_prefixes=runner.runner_prefixes())
    flow.step("floorplan", steps.floorplan)
    return flow


if __name__ == "__main__":
    wd = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.getcwd(), "runs", "ihp_ring")
    f = run(wd)
    print(f.steps["floorplan"].selected.outputs["pad_ring"])
