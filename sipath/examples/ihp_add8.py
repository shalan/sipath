"""Second-PDK example: a small soft macro on IHP SG13G2, routed to DEF + SPEF.

    python3 -m sipath run sipath/examples/ihp_add8.yaml [workdir]

``write_inputs`` generates the inputs the design file names: an 8-bit
registered ripple adder built from sg13g2 cells (the library has no full
adder: per bit p = a^b, g = a&b, s = p^c, carry = p&c | g with a21o), two
analog feed-through nets, a floorplan DEF on the CoreSite rows with pins on
the ORFS track grid (Metal3 left/right, Metal2 top/bottom), and an SDC. The
design file (``ihp_add8.yaml``) adds a bit-slice datapath (per bit: a and b
registers, p, g, s, carry; stage columns aligned), a cluster for the output
registers, and the steps.
"""
from __future__ import annotations

import os

from ..netlist import Module
from .designs import INPUTS, floorplan_def

C = "sg13g2_"
SDC = """\
create_clock -name clk -period 10.0 [get_ports clk]
set_clock_uncertainty 0.1 [get_clocks clk]
set_input_delay 1.0 -clock clk [get_ports {a[*] b[*]}]
set_output_delay 1.0 -clock clk [get_ports {sum[*]}]
set_driving_cell -lib_cell sg13g2_buf_2 [get_ports {a[*] b[*]}]
set_load 0.02 [get_ports {sum[*]}]
"""


def netlist() -> tuple[Module, dict]:
    m = Module("ihp_add8")
    clk = m.port("clk", "input")[0]
    a, b = m.port("a", "input", 8), m.port("b", "input", 8)
    ana_in, ana_out = m.port("ana_in", "inout", 2), m.port("ana_out", "inout", 2)
    s_out = m.port("sum", "output", 9)
    hi, lo = m.wire("u_tie.hi"), m.wire("u_tie.lo")
    m.inst("u_tie.th", C + "tiehi", L_HI=hi)
    m.inst("u_tie.tl", C + "tielo", L_LO=lo)

    def reg(name, d, q):
        m.inst(name, C + "dfrbpq_1", CLK=clk, D=d, RESET_B=hi, Q=q)

    slices, carry = [], lo
    sums = []
    for i in range(8):
        aq, bq = m.wire(f"u_in.a_q_{i}"), m.wire(f"u_in.b_q_{i}")
        reg(f"u_in.ra_{i}", a[i], aq)
        reg(f"u_in.rb_{i}", b[i], bq)
        p, g, s, co = (m.wire(f"u_add.{n}_{i}") for n in ("pw", "gw", "sw", "cw"))
        m.inst(f"u_add.p_{i}", C + "xor2_1", A=aq, B=bq, X=p)
        m.inst(f"u_add.g_{i}", C + "and2_1", A=aq, B=bq, X=g)
        m.inst(f"u_add.s_{i}", C + "xor2_1", A=p, B=carry, X=s)
        m.inst(f"u_add.c_{i}", C + "a21o_1", A1=p, A2=carry, B1=g, X=co)
        slices.append([f"u_in.ra_{i}", f"u_in.rb_{i}", f"u_add.p_{i}", f"u_add.g_{i}", f"u_add.s_{i}",
                       f"u_add.c_{i}"])
        sums.append(s)
        carry = co
    for i, s in enumerate(sums + [carry]):
        reg(f"u_out.rs_{i}", s, s_out[i])
    for i in range(2):
        m.assigns.append((ana_out[i], ana_in[i]))
    return m, {"slices": slices, "analog_nets": ana_in}


def write_inputs(out_dir=INPUTS) -> dict:
    os.makedirs(out_dir, exist_ok=True)
    m, meta = netlist()
    paths = {"netlist": os.path.join(out_dir, "ihp_add8.v"), "sdc": os.path.join(out_dir, "ihp_add8.sdc"),
             "floorplan_def": os.path.join(out_dir, "ihp_add8_floorplan.def")}
    with open(paths["netlist"], "w") as f:
        f.write("// generated by sipath.examples.ihp_add8 -- flat gate-level netlist (IHP SG13G2)\n" + m.to_verilog())
    with open(paths["sdc"], "w") as f:
        f.write(SDC)
    with open(paths["floorplan_def"], "w") as f:
        # CoreSite 0.48 x 3.78 um; ORFS tracks: Metal2 x pitch 0.48, Metal3 y pitch 0.42 (offset 0)
        f.write(floorplan_def(m, (120.0, 113.4), "CoreSite", 0.48, 3.78, margin_sites=21, margin_rows=3,
                              hpin=("Metal3", 0.42, 0.0, 0.1), vpin=("Metal2", 0.48, 0.0, 0.1)))
    return {**paths, **meta}
