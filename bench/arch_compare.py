"""amd64 under Rosetta vs native arm64: the same SiPath flows on two images (P1.1).

    python3 bench/arch_compare.py [gcd8 aes ...] [--explore-only] [--only amd64|arm64] [--table]

Each design runs twice, one after the other (run it on an otherwise idle
machine):

* amd64: the ORFS image (``openroad/orfs:latest``, linux/amd64: emulated by
  Rosetta on Apple silicon);
* arm64: LibreLane's image (``ghcr.io/librelane/librelane:3.0.16``,
  linux/arm64, native), also used for the Magic checks.

The images carry different tool builds (see each run's provenance), so the
results differ slightly; the comparison is of wall time per step, with each
run's own quality numbers alongside. Designs: an example name (its design
file, full flow) or a benchmark design already generated by
``bench/orfs_compare.py`` (``runs/bench/<d>/sipath/<d>.json``). Each runs in
full and in explore mode (``--explore``) unless ``--explore-only``.

Results go to runs/arch/<design>/<mode>_<arch>/ (the run, run.log,
time.json); ``--table`` only prints the table (runs/arch/compare.md) from
what is there. Uses only images already present; nothing is pulled.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "runs", "arch")
LIBRELANE = "ghcr.io/librelane/librelane:3.0.16"
ARCHES = {
    "amd64": {"SIPATH_OPENROAD_IMAGE": "openroad/orfs:latest", "SIPATH_PLATFORM": "linux/amd64",
              "SIPATH_OPENROAD_BINARY": ""},
    "arm64": {"SIPATH_OPENROAD_IMAGE": LIBRELANE, "SIPATH_PLATFORM": "linux/arm64",
              "SIPATH_OPENROAD_BINARY": "openroad", "SIPATH_MAGIC_IMAGE": LIBRELANE},
}


def design_file(d: str) -> str:
    for p in (os.path.join(ROOT, "sipath", "examples", f"{d}.yaml"),
              os.path.join(ROOT, "runs", "bench", d, "sipath", f"{d}.json")):
        if os.path.isfile(p):
            return p
    raise SystemExit(f"{d}: no example design file and no runs/bench/{d}/sipath/{d}.json "
                     f"(run bench/orfs_compare.py {d} first)")


def run(d: str, mode: str, arch: str) -> str:
    out = os.path.join(OUT, d, f"{mode}_{arch}")
    os.makedirs(out, exist_ok=True)
    env = {**os.environ, **ARCHES[arch]}
    if not env["SIPATH_OPENROAD_BINARY"]:
        env.pop("SIPATH_OPENROAD_BINARY")
    args = [sys.executable, "-m", "sipath", "run", design_file(d), os.path.join(out, "run"), "-v"]
    if mode == "explore":
        args.append("--explore")
    subprocess.run(["rm", "-rf", os.path.join(out, "run")])
    t0 = time.time()
    with open(os.path.join(out, "run.log"), "w") as f:
        rc = subprocess.run(args, cwd=ROOT, env=env, stdout=f, stderr=subprocess.STDOUT).returncode
    with open(os.path.join(out, "time.json"), "w") as f:
        json.dump({"exit": rc, "seconds": round(time.time() - t0, 1)}, f)
    return out


def result(out: str) -> dict | None:
    """Wall time, per-step seconds (selected attempts), signoff tool seconds
    and quality numbers of one run; None when it never ran."""
    tj = os.path.join(out, "time.json")
    if not os.path.isfile(tj):
        return None
    r = {**json.load(open(tj)), "steps": {}, "signoff": {}, "quality": {}, "failed": None}
    graph = os.path.join(out, "run", "graph.json")
    if not os.path.isfile(graph):  # a missing graph is a failed run
        r["failed"] = "no graph.json"
        return r
    g = json.load(open(graph))
    r["provenance"] = g.get("provenance", {})
    for a in g["attempts"]:
        if a.get("status") == "selected":
            r["steps"][a["step"]] = a.get("seconds")
            m = a.get("metrics", {})
            for k in ("synth_cells", "wns", "wirelength_um", "drc", "ppa_fmax_mhz", "ppa_std_area_um2", "signoff_pass"):
                if k in m:
                    r["quality"][k] = m[k]
            sj = (a.get("outputs") or {}).get("signoff")
            if isinstance(sj, str) and os.path.isfile(sj):
                r["signoff"] = json.load(open(sj)).get("seconds") or {}
        elif a.get("status") == "failed" and not r["failed"]:
            r["failed"] = f"{a['id']}: {(a.get('error') or '').strip().splitlines()[-1:]}"
    if r["exit"] and not r["failed"]:
        r["failed"] = f"exit {r['exit']}"
    return r


def fmt(x) -> str:
    return "-" if x is None else (f"{x:,.1f}" if isinstance(x, float) else str(x))


def table(designs: list[str]) -> str:
    lines = []
    for d in designs:
        for mode in ("full", "explore"):
            a, b = result(os.path.join(OUT, d, f"{mode}_amd64")), result(os.path.join(OUT, d, f"{mode}_arm64"))
            if not (a or b):
                continue
            lines += [f"### {d} ({mode})", "", "| step | amd64 (Rosetta) s | arm64 (native) s | speed-up |",
                      "|---|---|---|---|"]
            steps = list(dict.fromkeys([*(a or {}).get("steps", {}), *(b or {}).get("steps", {})]))
            rows = [(s, (a or {}).get("steps", {}).get(s), (b or {}).get("steps", {}).get(s)) for s in steps]
            checks = list(dict.fromkeys([*(a or {}).get("signoff", {}), *(b or {}).get("signoff", {})]))
            rows += [(f"signoff: {c}", (a or {}).get("signoff", {}).get(c), (b or {}).get("signoff", {}).get(c))
                     for c in checks]
            failed = not (a and b) or a["failed"] or b["failed"]
            rows.append(("**wall**", (a or {}).get("seconds"), (b or {}).get("seconds")))
            for name, x, y in rows:
                # a failed run's wall time stops early: no speed-up from it
                sp = "-" if (name == "**wall**" and failed) else (f"{x / y:.2f}x" if x and y else "-")
                lines.append(f"| {name} | {fmt(x)} | {fmt(y)} | {sp} |")
            lines.append("")
            for arch, r in (("amd64", a), ("arm64", b)):
                if r:
                    q = ", ".join(f"{k} {fmt(v)}" for k, v in r["quality"].items())
                    lines.append(f"- {arch}: {q or '-'}" + (f"; **failed** {r['failed']}" if r["failed"] else ""))
            lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    designs = [a for a in argv if not a.startswith("-") and a not in ARCHES] or ["gcd8"]
    arches = [argv[argv.index("--only") + 1]] if "--only" in argv else list(ARCHES)
    if "--table" not in argv:
        modes = ["explore"] if "--explore-only" in argv else ["explore", "full"]
        for d in designs:
            for mode in modes:
                for arch in arches:
                    print(f"{d} {mode} {arch} ...", flush=True)
                    out = run(d, mode, arch)
                    print(f"  {json.load(open(os.path.join(out, 'time.json')))}", flush=True)
    md = table(designs)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "compare.md"), "w") as f:
        f.write(md)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
